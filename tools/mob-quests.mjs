// mob-quests.mjs: builds addon/GrimoireSync/MobQuests.lua, the "which quests is this mob part of" table the
// addon's unit tooltip reads (addon 1.2). Every quest in Questie's Forever database, inverted per NPC:
//   GrimoireSyncMQ[npcId] = { {questId, 0}, ... }        -- 0 = you kill this mob for the quest
//                         = { {questId, itemId}, ... }   -- this mob drops an objective item
// The addon filters this against your live quest log, so quests you don't have cost nothing but file size.
// Source: QuestieDB (github.com/Questie/QuestieDB, GPL-3.0), cached in tools/.questdb by quest-data.mjs --fetch.
// Usage: node tools/mob-quests.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CACHE = path.join(ROOT, "tools", ".questdb");
const OUT = path.join(ROOT, "addon", "GrimoireSync", "MobQuests.lua");

// Same tiny literal-only Lua parser as quest-data.mjs (never executes anything).
function parseLua(src, i = 0){
  const ws = () => { while(i < src.length && /\s/.test(src[i])) i++; };
  function val(){
    ws(); const c = src[i];
    if(c === "{") return table();
    if(c === "'" || c === '"'){
      let s = "", q = c; i++;
      while(src[i] !== q){ if(src[i] === "\\"){ i++; const e = src[i]; s += e === "n" ? "\n" : e; } else s += src[i]; i++; }
      i++; return s;
    }
    const m = /^(-?\d+(?:\.\d+)?(?:e-?\d+)?|nil|true|false)/.exec(src.slice(i, i + 40));
    if(!m) throw new Error("Lua parse error at " + i + ": " + src.slice(i, i + 30));
    i += m[0].length;
    return m[0] === "nil" ? null : m[0] === "true" ? true : m[0] === "false" ? false : +m[0];
  }
  function table(){
    i++; const arr = []; let obj = null;
    for(;;){
      ws();
      if(src[i] === "}"){ i++; break; }
      if(src[i] === ","){ i++; continue; }
      if(src[i] === "["){ i++; const k = val(); ws(); i++; ws(); i++; const v = val(); (obj ||= {})[k] = v; continue; }
      arr.push(val());
    }
    if(obj){ arr.forEach((v, n) => { obj[n + 1] = v; }); return obj; }
    return arr;
  }
  return val();
}
function each(file, fn){
  for(const line of fs.readFileSync(path.join(CACHE, file), "utf8").split("\n")){
    const m = /^\s*\[(\d+)\]\s*=\s*\{/.exec(line); if(!m) continue;
    let v; try{ v = parseLua(line, line.indexOf("{")); }catch(e){ continue; }
    fn(+m[1], v);
  }
}

if(!fs.existsSync(path.join(CACHE, "foreverQuestDB.lua"))){ console.error("Run node tools/quest-data.mjs --fetch first."); process.exit(1); }
const want = new Map();   // itemId -> [questIds] for objective items
const map = new Map();    // npcId -> Set("q,kind")
const add = (npc, q, kind) => { if(!npc) return; if(!map.has(npc)) map.set(npc, new Set()); map.get(npc).add(q + "," + kind); };
each("foreverQuestDB.lua", (qid, q) => {
  const ob = q[9] || [];
  for(const o of ob[0] || []) add(o[0], qid, 0);
  for(const k of ob[4] || []) for(const n of k[0] || []) add(n, qid, 0);   // kill credit groups ("Syndicate slain")
  for(const o of ob[2] || []){ if(!want.has(o[0])) want.set(o[0], []); want.get(o[0]).push(qid); }
});
each("foreverItemDB.lua", (iid, it) => {
  const qs = want.get(iid); if(!qs) return;
  // Items most mobs drop (cloth for donation quests, Light Leather) are world loot, not a quest target: tagging
  // every mob with them would bury the real ones and tripled the file (1.1 MB). 40+ droppers = skipped.
  if((it[1] || []).length > 40) return;
  for(const n of it[1] || []) for(const q of qs) add(n, q, iid);   // it[1] = npcDrops
});
const ids = [...map.keys()].sort((a, b) => a - b);
const body = ids.map(n => `[${n}]={${[...map.get(n)].map(s => `{${s}}`).join(",")}},`).join("\n");
const lua = `-- Generated by tools/mob-quests.mjs from QuestieDB's Forever data (GPL-3.0). Don't edit by hand.\n` +
  `-- npcId -> { {questId, 0 = kill it | itemId it drops}, ... }\nGrimoireSyncMQ = {\n${body}\n}\n`;
fs.writeFileSync(OUT, lua);
console.log(`MobQuests.lua: ${ids.length} NPCs, ${(lua.length / 1024).toFixed(0)} KB`);
